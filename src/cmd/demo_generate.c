#include <assert.h>
#include <stdio.h>

typedef char demo_generate_masks_fit_uint16[P8_PAD_BUTTON_COUNT <= 16 ? 1 : -1];
typedef char demo_generate_text_sizes_agree[DEMO_DATA_CAPTION_TEXT_SIZE == PAD_CAPTION_TEXT_SIZE ? 1 : -1];

enum { PER_LINE = 16 };

/* `\?` too: -std=c99 enables trigraphs, so "??/" would compile to another character. */
static void write_c_string(FILE *out, const char *text) {
    fputc('"', out);
    for (const char *c = text; *c != '\0'; c++) {
        if (*c == '\n') {
            fputs("\\n", out);
        } else if (*c == '\\' || *c == '"' || *c == '?') {
            fputc('\\', out);
            fputc(*c, out);
        } else {
            fputc(*c, out);
        }
    }
    fputc('"', out);
}

static void write_unit(FILE *out, const char *input_path, const demo_source_t *source) {
    const replay_source_t *replay = &source->replay;
    int frame_count = replay_source_frame_count(replay);
    assert(replay->initial_save_count > 0 && frame_count > 0 && source->caption_count > 0);
    fprintf(out, "/* Generated by demo_generate from %s. Do not edit. */\n", input_path);
    fprintf(out, "#include \"game/demo_data.h\"\n\n");
    fprintf(out, "const uint8_t demo_data_record[] = {\n");
    for (int i = 0; i < replay->initial_save_count; i++) {
        fprintf(out, "%s0x%02x,%s", i % PER_LINE == 0 ? "    " : " ", replay->initial_save[i],
                i % PER_LINE == PER_LINE - 1 || i == replay->initial_save_count - 1 ? "\n" : "");
    }
    fprintf(out, "};\n\n");
    fprintf(out, "const uint16_t demo_data_pad_buttons[] = {\n");
    for (int i = 0; i < frame_count; i++) {
        fprintf(out, "%s%d,%s", i % PER_LINE == 0 ? "    " : " ", replay->recording.frames[i].pad_buttons,
                i % PER_LINE == PER_LINE - 1 || i == frame_count - 1 ? "\n" : "");
    }
    fprintf(out, "};\n\n");
    fprintf(out, "const demo_data_caption_t demo_data_captions[] = {\n");
    for (int i = 0; i < source->caption_count; i++) {
        fprintf(out, "    { %d, %d, ", source->captions[i].from, source->captions[i].to);
        write_c_string(out, source->captions[i].text);
        fprintf(out, " },\n");
    }
    fprintf(out, "};\n\n");
    fprintf(out, "const int demo_data_record_count = %d;\n", replay->initial_save_count);
    fprintf(out, "const int demo_data_frame_count = %d;\n", frame_count);
    fprintf(out, "const int demo_data_caption_count = %d;\n", source->caption_count);
}

int main(int argc, char **argv) {
    if (argc != 3) {
        fprintf(stderr, "usage: demo_generate <demo.json> <output.c>\n");
        return 2;
    }
    const char *input_path = argv[1];
    const char *output_path = argv[2];
    static demo_source_t source;
    char error[512];
    if (!demo_source_load(&source, input_path, error, sizeof error)) {
        fprintf(stderr, "%s\n", error);
        return 1;
    }
    char temporary_path[4096];
    if (snprintf(temporary_path, sizeof temporary_path, "%s.tmp", output_path) >= (int)sizeof temporary_path) {
        fprintf(stderr, "%s: path too long\n", output_path);
        demo_source_close(&source);
        return 1;
    }
    FILE *out = fopen(temporary_path, "w");
    if (out == NULL) {
        fprintf(stderr, "%s: cannot write\n", temporary_path);
        demo_source_close(&source);
        return 1;
    }
    write_unit(out, input_path, &source);
    demo_source_close(&source);
    int failed = ferror(out);
    if (fclose(out) != 0 || failed) {
        fprintf(stderr, "%s: cannot write\n", temporary_path);
        remove(temporary_path);
        return 1;
    }
    if (rename(temporary_path, output_path) != 0) {
        fprintf(stderr, "%s: cannot rename to %s\n", temporary_path, output_path);
        remove(temporary_path);
        return 1;
    }
    return 0;
}
