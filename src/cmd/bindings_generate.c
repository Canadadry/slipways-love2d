#include "game/bindings.h"
#include "p8/input.h"

#include <ctype.h>
#include <stdio.h>
#include <string.h>

enum { INPUT_LIMIT = 65536 };

static int read_input(const char *path, char *text) {
    FILE *file = fopen(path, "rb");
    if (file == NULL) {
        fprintf(stderr, "%s: cannot read\n", path);
        return 0;
    }
    size_t length = fread(text, 1, INPUT_LIMIT + 1, file);
    int failed = ferror(file);
    fclose(file);
    if (failed) {
        fprintf(stderr, "%s: cannot read\n", path);
        return 0;
    }
    if (length > INPUT_LIMIT) {
        fprintf(stderr, "%s: larger than %d bytes\n", path, INPUT_LIMIT);
        return 0;
    }
    text[length] = '\0';
    return 1;
}

static void write_upper(FILE *out, const char *name) {
    for (const char *c = name; *c != '\0'; c++) {
        fputc(toupper((unsigned char)*c), out);
    }
}

static void write_mask(FILE *out, int mask) {
    const char *separator = "";
    for (int button = 1; button <= P8_PAD_BUTTON_COUNT; button++) {
        if (mask & (1 << (button - 1))) {
            fprintf(out, "%sP8_PAD_BUTTON_%d", separator, button);
            separator = " | ";
        }
    }
}

typedef enum { UNIT_COMPILED, UNIT_PERSONAL, UNIT_DEFAULT } unit_kind_t;

static void write_unit(FILE *out, const char *input_path, const bindings_t *bindings, unit_kind_t kind) {
    fprintf(out, "/* Generated by bindings_generate from %s. Do not edit. */\n", input_path);
    fprintf(out, "#include \"game/bindings.h\"\n#include \"p8/input.h\"\n\n");
    fprintf(out, "const bindings_t %s = { .masks = {\n", kind == UNIT_DEFAULT ? "bindings_default" : "bindings_compiled");
    int written = 0;
    for (int mode = 0; mode < BINDINGS_MODE_COUNT; mode++) {
        int mode_open = 0;
        for (int action = 0; action < BINDINGS_ACTION_COUNT; action++) {
            int mask = bindings_mask(bindings, (bindings_mode_t)mode, (bindings_action_t)action);
            if (mask == 0) {
                continue;
            }
            if (!mode_open) {
                fprintf(out, "    [BINDINGS_MODE_");
                write_upper(out, bindings_mode_name((bindings_mode_t)mode));
                fprintf(out, "] = {\n");
                mode_open = 1;
            }
            fprintf(out, "        [BINDINGS_ACTION_");
            write_upper(out, bindings_action_name((bindings_action_t)action));
            fprintf(out, "] = ");
            write_mask(out, mask);
            fprintf(out, ",\n");
            written = 1;
        }
        if (mode_open) {
            fprintf(out, "    },\n");
        }
    }
    if (!written) {
        fprintf(out, "    { 0 },\n");
    }
    fprintf(out, "} };\n");
    if (kind != UNIT_DEFAULT) {
        fprintf(out, "const int bindings_compiled_personal = %d;\n", kind == UNIT_PERSONAL);
    }
}

int main(int argc, char **argv) {
    unit_kind_t kind = UNIT_COMPILED;
    int option = argc == 4;
    if (option && strcmp(argv[1], "--personal") == 0) {
        kind = UNIT_PERSONAL;
    } else if (option && strcmp(argv[1], "--default") == 0) {
        kind = UNIT_DEFAULT;
    }
    if (argc != 3 + option || (option && kind == UNIT_COMPILED)) {
        fprintf(stderr, "usage: bindings_generate [--personal | --default] <input.cfg> <output.c>\n");
        return 2;
    }
    const char *input_path = argv[1 + option];
    const char *output_path = argv[2 + option];
    static char text[INPUT_LIMIT + 1];
    if (!read_input(input_path, text)) {
        return 1;
    }
    bindings_t bindings;
    bindings_error_t error;
    if (!bindings_parse(input_path, text, &bindings, &error)) {
        fprintf(stderr, "%s\n", error.text);
        return 1;
    }
    char temporary_path[4096];
    if (snprintf(temporary_path, sizeof temporary_path, "%s.tmp", output_path) >= (int)sizeof temporary_path) {
        fprintf(stderr, "%s: path too long\n", output_path);
        return 1;
    }
    FILE *out = fopen(temporary_path, "w");
    if (out == NULL) {
        fprintf(stderr, "%s: cannot write\n", temporary_path);
        return 1;
    }
    write_unit(out, input_path, &bindings, kind);
    int failed = ferror(out);
    if (fclose(out) != 0 || failed) {
        fprintf(stderr, "%s: cannot write\n", temporary_path);
        remove(temporary_path);
        return 1;
    }
    if (rename(temporary_path, output_path) != 0) {
        fprintf(stderr, "%s: cannot rename to %s\n", temporary_path, output_path);
        remove(temporary_path);
        return 1;
    }
    return 0;
}
