-- Copy of src/engine/zone_sizes.h, which has no .c: its macros as fields.
local zone = require("engine.zone")

local M = {}

M.SIZEOF = {
  ["void *"] = 8,
  uint16_t = 2,
}
local SIZEOF = M.SIZEOF

M.ENTITY_TABLE_CAP = 512
M.ENTITY_TABLE_BYTES =
  zone.ZONE_BYTES(M.ENTITY_TABLE_CAP * (SIZEOF["void *"] + 2 * SIZEOF.uint16_t))

M.FRAME_ZONE_BYTES = 20256
M.UI_ZONE_BYTES = 208272
M.PARTICLES_ZONE_BYTES = 73067
M.GENERATION_ZONE_BYTES = 462520 + M.ENTITY_TABLE_BYTES
M.LOAD_ZONE_BYTES = 24984
M.GAME_ZONE_BYTES = M.GENERATION_ZONE_BYTES + M.LOAD_ZONE_BYTES

M.HEADER_ID_BYTES = 3720 + 32 + 304

M.ZONE_BUDGET_BYTES = 768 * 1024 + M.ENTITY_TABLE_BYTES + M.HEADER_ID_BYTES

M.ZONE_BUDGET_USED_BYTES =
  M.FRAME_ZONE_BYTES + M.UI_ZONE_BYTES + M.PARTICLES_ZONE_BYTES + M.GAME_ZONE_BYTES

assert(M.ZONE_BUDGET_USED_BYTES <= M.ZONE_BUDGET_BYTES, "zone budget exceeded")

assert(M.LOAD_ZONE_BYTES < M.GAME_ZONE_BYTES
  and M.GENERATION_ZONE_BYTES + M.LOAD_ZONE_BYTES == M.GAME_ZONE_BYTES,
  "load zone outside the game zone")

return M
